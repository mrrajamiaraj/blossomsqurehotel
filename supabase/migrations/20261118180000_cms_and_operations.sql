-- Swaps an image for a new upload everywhere it is used (live pages, drafts,
-- room galleries), then deletes the old record; the app removes the old file.
create or replace function public.admin_replace_media(p_old uuid, p_new uuid)
returns text
language plpgsql
security definer
set search_path = public
as $$
declare
  o media_assets%rowtype;
  n media_assets%rowtype;
begin
  select * into o from media_assets where id = p_old for update;
  select * into n from media_assets where id = p_new for update;
  if o.id is null or n.id is null or o.id = n.id then
    raise exception 'NOT_FOUND';
  end if;
  perform public._require_media(o.bucket);
  perform public._require_media(n.bucket);
  update site_content set body = replace(body::text, o.url, n.url)::jsonb
  where strpos(body::text, o.url) > 0;
  update site_content set draft_body = replace(draft_body::text, o.url, n.url)::jsonb
  where strpos(coalesce(draft_body::text, ''), o.url) > 0;
  update room_types set gallery = array_replace(gallery, o.url, n.url) where o.url = any (gallery);
  update media_assets set alt = case when n.alt = '' then o.alt else n.alt end, folder = o.folder, updated_at = now() where id = n.id;
  delete from media_assets where id = o.id;
  return o.path;
end;
$$;

