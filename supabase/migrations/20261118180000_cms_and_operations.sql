-- Content management and daily operations.
--
--   Website content   draft → publish workflow on site_content (drafts are
--                     never readable by visitors), version history, restore.
--   Media library     media_assets: every uploaded image (site-media and
--                     room-photos buckets), with usage checks before delete
--                     and "replace everywhere".
--   Room setup        create room types (with their standard rate plan),
--                     seasonal rates with clear overlap errors.
--   Housekeeping      room status dirty / cleaning / clean / inspected (plus
--                     occupied and out of service, which are derived); task
--                     assignment; maintenance issue reports; a board view
--                     that shows occupancy without guest details.
--   Promotions        automatic offers (no code) and codes; stackable or
--                     exclusive; booking windows; per-offer and overall caps.
--                     The guest always gets the best allowed combination,
--                     priced by the database (_quote).
--
-- Error codes: CONTENT_CONFLICT, NOTHING_TO_PUBLISH, BAD_CONTENT, NOT_FOUND,
-- MEDIA_IN_USE, BAD_MEDIA, BAD_ROOM_TYPE, SEASON_OVERLAP, BAD_SEASON, BAD_TASK,
-- NOT_ALLOWED, BAD_PROMO, PROMO_CODE_TAKEN, PROMO_IN_USE, PRICE_CHANGED.
--
-- Rollback: supabase/rollbacks/20261118180000_cms_and_operations.down.sql
-- (generated by scripts/gen-cms-rollback.mts, verified by tests/db/cms-rollback.test.ts).

