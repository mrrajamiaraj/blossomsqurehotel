-- Saves a draft. p_base is the draft stamp the editor started from; if a
-- colleague saved in between, CONTENT_CONFLICT (nothing is overwritten).
create or replace function public.admin_save_content_draft(p_key text, p_locale text, p_title text, p_body jsonb, p_base timestamptz)
returns timestamptz
language plpgsql
security definer
set search_path = public
as $$
declare
  c site_content%rowtype;
  v_now timestamptz := clock_timestamp();
begin
  perform public._require('content.manage');
  perform public._content_key_ok(p_key, p_locale);
  if p_body is null or jsonb_typeof(p_body) <> 'object' or pg_column_size(p_body) > 200000 then
    raise exception 'BAD_CONTENT';
  end if;
  select * into c from site_content where key = p_key and locale = p_locale for update;
  if found then
    if c.draft_updated_at is not null and p_base is distinct from c.draft_updated_at then
      raise exception 'CONTENT_CONFLICT';
    end if;
    update site_content set draft_title = nullif(left(trim(coalesce(p_title, '')), 200), ''), draft_body = p_body,
           draft_updated_at = v_now, draft_updated_by = auth.uid()
    where key = p_key and locale = p_locale;
  else
    insert into site_content (key, locale, title, body, status, draft_title, draft_body, draft_updated_at, draft_updated_by)
    values (p_key, p_locale, null, '{}'::jsonb, 'draft', nullif(left(trim(coalesce(p_title, '')), 200), ''), p_body, v_now, auth.uid());
  end if;
  return v_now;
end;
$$;

-- Makes the draft live and keeps the previous published version in history.
create or replace function public.admin_publish_content(p_key text, p_locale text, p_base timestamptz)
returns integer
language plpgsql
security definer
set search_path = public
as $$
declare
  c site_content%rowtype;
begin
  perform public._require('content.manage');
  perform public._content_key_ok(p_key, p_locale);
  select * into c from site_content where key = p_key and locale = p_locale for update;
  if not found or c.draft_body is null then
    raise exception 'NOTHING_TO_PUBLISH';
  end if;
  if p_base is distinct from c.draft_updated_at then
    raise exception 'CONTENT_CONFLICT';
  end if;
  update site_content set title = c.draft_title, body = c.draft_body, status = 'published', version = c.version + 1,
         draft_title = null, draft_body = null, draft_updated_at = null, draft_updated_by = null
  where key = p_key and locale = p_locale;
  insert into site_content_versions (key, locale, version, title, body, published_by)
  values (p_key, p_locale, c.version + 1, c.draft_title, c.draft_body, auth.uid());
  return c.version + 1;
end;
$$;

