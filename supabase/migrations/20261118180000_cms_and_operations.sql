-- A new room category, unpublished until rooms and photos are added.
create or replace function public.admin_create_room_type(
  p_name text, p_tag text, p_bed text, p_sleeps integer, p_price integer, p_weekend_price integer, p_blurb text, p_description text
)
returns uuid
language plpgsql
security definer
set search_path = public
as $$
declare
  v_name text := trim(coalesce(p_name, ''));
  v_base text;
  v_slug text;
  v_n    integer := 1;
  v_id   uuid;
begin
  perform public._require('rooms.manage');
  if char_length(v_name) not between 3 and 60 or p_tag not in ('SUITE', 'DELUXE')
     or char_length(trim(coalesce(p_bed, ''))) not between 2 and 80
     or p_sleeps is null or p_sleeps not between 1 and 10
     or p_price is null or p_price not between 500 and 1000000
     or (p_weekend_price is not null and p_weekend_price not between 500 and 1000000) then
    raise exception 'BAD_ROOM_TYPE';
  end if;
  v_base := trim(both '-' from regexp_replace(lower(v_name), '[^a-z0-9]+', '-', 'g'));
  if v_base = '' then
    raise exception 'BAD_ROOM_TYPE';
  end if;
  v_slug := v_base;
  while exists (select 1 from room_types where slug = v_slug) loop
    v_n := v_n + 1;
    v_slug := v_base || '-' || v_n;
  end loop;
  insert into room_types (slug, name, tag, bed, sleeps, floor, view, price_bdt, weekend_price_bdt, blurb, description, sort_order, is_published)
  values (v_slug, v_name, p_tag, trim(p_bed), p_sleeps, '', '', p_price, p_weekend_price,
          left(trim(coalesce(p_blurb, '')), 240), left(trim(coalesce(p_description, '')), 1500),
          coalesce((select max(sort_order) + 1 from room_types), 1), false)
  returning id into v_id;
  insert into rate_plans (room_type_id, code, name, description)
  values (v_id, 'STANDARD', 'Standard rate', 'Breakfast included. Pay at the hotel or send an advance.');
  return v_id;
end;
$$;

-- Adds or edits a seasonal price. Overlapping active seasons are refused with a clear code.
create or replace function public.admin_save_seasonal_rate(
  p_id uuid, p_room_type uuid, p_name text, p_starts date, p_ends date, p_price integer, p_weekend_price integer, p_active boolean
)
returns uuid
language plpgsql
security definer
set search_path = public
as $$
declare
  v_id uuid;
begin
  perform public._require('rates.manage');
  if not exists (select 1 from room_types where id = p_room_type) then
    raise exception 'NOT_FOUND';
  end if;
  if char_length(trim(coalesce(p_name, ''))) not between 2 and 80 or p_starts is null or p_ends is null
     or p_ends <= p_starts or p_ends - p_starts > 366
     or p_price is null or p_price not between 500 and 1000000
     or (p_weekend_price is not null and p_weekend_price not between 500 and 1000000) then
    raise exception 'BAD_SEASON';
  end if;
  begin
    if p_id is null then
      insert into seasonal_rates (room_type_id, name, starts_on, ends_on, price_bdt, weekend_price_bdt, is_active, created_by)
      values (p_room_type, trim(p_name), p_starts, p_ends, p_price, p_weekend_price, coalesce(p_active, true), auth.uid())
      returning id into v_id;
    else
      update seasonal_rates set room_type_id = p_room_type, name = trim(p_name), starts_on = p_starts, ends_on = p_ends,
             price_bdt = p_price, weekend_price_bdt = p_weekend_price, is_active = coalesce(p_active, true)
      where id = p_id
      returning id into v_id;
      if v_id is null then
        raise exception 'NOT_FOUND';
      end if;
    end if;
  exception when exclusion_violation then
    raise exception 'SEASON_OVERLAP';
  end;
  return v_id;
end;
$$;

create or replace function public.admin_delete_seasonal_rate(p_id uuid)
returns void language plpgsql security definer set search_path = public as $$
begin
  perform public._require('rates.manage');
  delete from seasonal_rates where id = p_id;
  if not found then
    raise exception 'NOT_FOUND';
  end if;
end;
$$;

