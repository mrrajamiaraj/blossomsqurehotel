-- Where an image is used: content sections (published or draft) and room galleries.
create or replace function public.admin_media_usage(p_id uuid)
returns table (kind text, ref text, label text)
language plpgsql
stable
security definer
set search_path = public
as $$
declare
  m media_assets%rowtype;
begin
  select * into m from media_assets where id = p_id;
  if not found then
    raise exception 'NOT_FOUND';
  end if;
  perform public._require_media(m.bucket);
  return query
    select 'content'::text, c.key, c.key || case when strpos(c.body::text, m.url) > 0 then '' else ' (draft)' end
    from site_content c
    where strpos(c.body::text, m.url) > 0 or strpos(coalesce(c.draft_body::text, ''), m.url) > 0
    union all
    select 'room_type', rt.slug, rt.name from room_types rt where m.url = any (rt.gallery);
end;
$$;

-- Deletes the record of an unused image; the app then removes the file.
create or replace function public.admin_delete_media(p_id uuid)
returns text
language plpgsql
security definer
set search_path = public
as $$
declare
  m media_assets%rowtype;
begin
  select * into m from media_assets where id = p_id for update;
  if not found then
    raise exception 'NOT_FOUND';
  end if;
  perform public._require_media(m.bucket);
  if exists (select 1 from public.admin_media_usage(p_id)) then
    raise exception 'MEDIA_IN_USE';
  end if;
