-- Null when the offer applies to this stay; otherwise why not.
create or replace function public._promo_applies(p promotions, p_in date, p_out date, p_types uuid[], p_exclude_booking uuid)
returns text
language plpgsql
stable
security definer
set search_path = public
as $$
declare
  v_today date := public._today();
  v_used  integer;
begin
  if p.id is null or not p.is_active or p.ends_on <= v_today
     or (p.bookable_from is not null and v_today < p.bookable_from)
     or (p.bookable_until is not null and v_today > p.bookable_until) then
    return 'PROMO_INVALID';
  end if;
  if p_in < p.starts_on or p_in >= p.ends_on or (p_out - p_in) < p.min_nights
     or (cardinality(p.room_type_ids) > 0 and not (p.room_type_ids && p_types)) then
    return 'PROMO_NOT_APPLICABLE';
  end if;
  if p.max_redemptions is not null then
    select count(*) into v_used from booking_promotions bp join bookings b on b.id = bp.booking_id
    where bp.promotion_id = p.id and b.status not in ('cancelled', 'no_show')
      and (p_exclude_booking is null or b.id <> p_exclude_booking);
    if v_used >= p.max_redemptions then
      return 'PROMO_EXHAUSTED';
    end if;
  end if;
  return null;
end;
$$;

-- Resolves a promo code (kept for callers that check a code on its own).
create or replace function public._promotion_for(p_code text, p_in date, p_out date, p_types uuid[], p_strict boolean)
returns promotions
