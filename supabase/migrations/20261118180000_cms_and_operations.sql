-- Stamps only; publishing is done by admin_publish_content.
create or replace function public._site_content_stamp()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  new.updated_at := now();
  new.updated_by := auth.uid();
  if new.status = 'published' and (tg_op = 'INSERT' or old.status is distinct from 'published' or old.version is distinct from new.version) then
    new.published_at := now();
  end if;
  return new;
end;
$$;

create or replace function public._content_key_ok(p_key text, p_locale text)
returns void language plpgsql immutable set search_path = public as $$
begin
  if p_key is null or p_key !~ '^[a-z0-9_.-]{2,80}$' or p_locale is null or p_locale not in ('en', 'bn') then
    raise exception 'BAD_CONTENT';
  end if;
end;
$$;

