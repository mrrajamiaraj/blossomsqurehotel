create table public.media_assets (
  id         uuid primary key default gen_random_uuid(),
  bucket     text not null check (bucket in ('site-media', 'room-photos')),
  path       text not null check (path ~ '^[A-Za-z0-9][A-Za-z0-9/._-]{2,199}$' and path !~ '\.\.'),
  url        text not null check (url ~ '^https://' and char_length(url) <= 500),
  alt        text not null default '' check (char_length(alt) <= 200),
  folder     text not null default 'general' check (folder ~ '^[a-z0-9-]{2,40}$'),
  width      integer check (width is null or width between 1 and 12000),
  height     integer check (height is null or height between 1 and 12000),
  bytes      integer check (bytes is null or bytes between 1 and 10485760),
  mime       text not null check (mime in ('image/jpeg', 'image/png', 'image/webp', 'image/avif')),
  created_by uuid references auth.users (id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (bucket, path),
  constraint media_assets_url_matches check (right(url, char_length(bucket) + char_length(path) + 2) = '/' || bucket || '/' || path)
);
create index media_assets_folder_idx on public.media_assets (folder, created_at desc);

create or replace function public._require_media(p_bucket text)
returns void language plpgsql stable security definer set search_path = public as $$
begin
  if p_bucket = 'room-photos' and public.has_permission('rooms.manage') then
    return;
  end if;
  perform public._require('content.manage');
end;
$$;

-- Records a file the app has just uploaded to Storage (the object must exist).
create or replace function public.admin_register_media(
  p_bucket text, p_path text, p_url text, p_alt text, p_folder text, p_width integer, p_height integer, p_bytes integer, p_mime text
)
returns uuid
language plpgsql
security definer
set search_path = public
as $$
declare
  v_id uuid;
begin
  perform public._require_media(p_bucket);
  if not exists (select 1 from storage.objects where bucket_id = p_bucket and name = p_path) then
    raise exception 'BAD_MEDIA';
  end if;
