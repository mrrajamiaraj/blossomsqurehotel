-- What one offer takes off these lines: its percentage (or fixed amount, once
-- per stay) of the nights it covers, on the room types it covers, capped by
-- its own maximum.
create or replace function public._promo_discount(p promotions, p_lines jsonb)
returns integer
language plpgsql
stable
security definer
set search_path = public
as $$
declare
  v_elig integer;
  v_disc integer;
begin
  select coalesce(sum((n ->> 'rate')::integer), 0) into v_elig
  from jsonb_array_elements(p_lines) l, jsonb_array_elements(l -> 'nights') n
  where (cardinality(p.room_type_ids) = 0 or (l ->> 'room_type_id')::uuid = any (p.room_type_ids))
    and (n ->> 'night')::date >= p.starts_on and (n ->> 'night')::date < p.ends_on;
  if v_elig <= 0 then
    return 0;
  end if;
  v_disc := case p.discount_type when 'percent' then round(v_elig * p.discount_value / 100.0)::integer
                                 else least(p.discount_value, v_elig) end;
  if p.max_discount_bdt is not null then
    v_disc := least(v_disc, p.max_discount_bdt);
  end if;
  return greatest(v_disc, 0);
end;
$$;

-- The full price of a reservation, computed only here.
--
-- Offers: the guest's code (if any) plus every automatic offer that applies.
-- Stackable offers add up; an exclusive offer stands alone. The guest gets
-- whichever is larger: all applicable stackable offers together, or the
-- single best exclusive one. The total discount never exceeds the hotel's
-- max_discount_percent of the room charges. code_status tells the guest
-- whether their code was used ('applied') or a better offer won ('not_better').
create or replace function public._quote(p_types uuid[], p_plans uuid[], p_in date, p_out date, p_promo text, p_strict boolean, p_exclude_booking uuid)
returns jsonb
language plpgsql
stable
security definer
set search_path = public
as $$
declare
  st          hotel_settings%rowtype;
  p           promotions%rowtype;
  code_p      promotions%rowtype;
  v_err       text;
  i           integer;
  v_lines     jsonb := '[]'::jsonb;
  v_nights    jsonb;
  v_line_sub  integer;
  v_sub       integer := 0;
  v_cands     jsonb := '[]'::jsonb;
  v_d         integer;
  v_stack     integer;
  v_best      jsonb;
  v_chosen    jsonb := '[]'::jsonb;
  v_applied   jsonb := '[]'::jsonb;
  v_cap       integer;
  v_left      integer;
  c           jsonb;
  v_take      integer;
  v_disc      integer := 0;
  v_svc       integer := 0;
  v_vat       integer := 0;
  v_total     integer;
  v_code_status text;
  rt          room_types%rowtype;
  rp          rate_plans%rowtype;
begin
  select * into st from hotel_settings where id = 1;

  for i in 1 .. coalesce(array_length(p_types, 1), 0) loop
    select * into rt from room_types where id = p_types[i];
    rp := null;
    if p_plans[i] is not null then
      select * into rp from rate_plans where id = p_plans[i];
    end if;
    select jsonb_agg(public._night_rate(p_types[i], p_plans[i], d::date) order by d)
      into v_nights from generate_series(p_in, p_out - 1, interval '1 day') d;
    select coalesce(sum((n ->> 'rate')::integer), 0) into v_line_sub from jsonb_array_elements(v_nights) n;
    v_sub := v_sub + v_line_sub;
    v_lines := v_lines || jsonb_build_array(jsonb_build_object(
      'line', i, 'room_type_id', rt.id, 'room_type', rt.slug, 'name', rt.name, 'sleeps', rt.sleeps,
      'rate_plan_id', rp.id, 'rate_plan', rp.code, 'rate_plan_name', rp.name,
      'nights', v_nights, 'subtotal', v_line_sub));
  end loop;

  -- The guest's code.
  if p_promo is not null and btrim(p_promo) <> '' then
    select * into code_p from promotions where code is not null and upper(code) = upper(btrim(p_promo));
    v_err := case when code_p.id is null then 'PROMO_INVALID' else public._promo_applies(code_p, p_in, p_out, p_types, p_exclude_booking) end;
    if v_err is not null then
      if p_strict then raise exception '%', v_err; end if;
      code_p := null;
      v_code_status := 'not_applicable';
    end if;
  end if;

  -- Candidates: the code, then automatic offers.
  for p in
    select * from promotions
    where (code_p.id is not null and id = code_p.id)
       or (auto_apply and is_active and ends_on > public._today())
    order by (id = code_p.id) desc nulls last, created_at, id
  loop
    if p.id is distinct from code_p.id and public._promo_applies(p, p_in, p_out, p_types, p_exclude_booking) is not null then
      continue;
    end if;
    v_d := public._promo_discount(p, v_lines);
    if v_d > 0 then
      v_cands := v_cands || jsonb_build_array(jsonb_build_object(
        'id', p.id, 'code', p.code, 'name', p.name, 'stackable', p.stackable, 'discount', v_d, 'is_code', coalesce(p.id = code_p.id, false)));
    elsif p.id = code_p.id then
      v_code_status := 'not_applicable';
    end if;
  end loop;

  -- Best allowed combination.
  select coalesce(sum((x ->> 'discount')::integer), 0) into v_stack from jsonb_array_elements(v_cands) x where (x ->> 'stackable')::boolean;
  select x into v_best from jsonb_array_elements(v_cands) x where not (x ->> 'stackable')::boolean
  order by (x ->> 'discount')::integer desc, (x ->> 'is_code')::boolean desc limit 1;
  if v_stack > 0 and v_stack >= coalesce((v_best ->> 'discount')::integer, 0) then
    select coalesce(jsonb_agg(x order by (x ->> 'discount')::integer desc, (x ->> 'is_code')::boolean desc), '[]'::jsonb)
      into v_chosen from jsonb_array_elements(v_cands) x where (x ->> 'stackable')::boolean;
  elsif v_best is not null then
    v_chosen := jsonb_build_array(v_best);
  end if;

  -- Overall cap, shared out in order.
  v_cap := floor(v_sub * coalesce(st.max_discount_percent, 50) / 100.0)::integer;
  v_left := v_cap;
  for c in select * from jsonb_array_elements(v_chosen) loop
    v_take := least((c ->> 'discount')::integer, v_left);
    exit when v_take <= 0;
    v_applied := v_applied || jsonb_build_array(c || jsonb_build_object('discount', v_take));
    v_left := v_left - v_take;
  end loop;
  v_disc := v_cap - v_left;

  if code_p.id is not null and v_code_status is null then
    v_code_status := case when exists (select 1 from jsonb_array_elements(v_applied) x where (x ->> 'is_code')::boolean)
                          then 'applied' else 'not_better' end;
  end if;

  if st.service_charge_percent is not null then
    v_svc := round((v_sub - v_disc) * st.service_charge_percent / 100.0)::integer;
  end if;
  if st.vat_percent is not null then
    v_vat := round((v_sub - v_disc + v_svc) * st.vat_percent / 100.0)::integer;
  end if;
  v_total := v_sub - v_disc + v_svc + v_vat;

  return jsonb_build_object(
    'currency', 'BDT', 'check_in', p_in, 'check_out', p_out, 'nights', p_out - p_in,
    'lines', v_lines, 'subtotal', v_sub, 'discount', v_disc,
    'promotion', case when jsonb_array_length(v_applied) = 0 then null
                      else jsonb_build_object('id', v_applied -> 0 ->> 'id', 'code', v_applied -> 0 ->> 'code', 'name', v_applied -> 0 ->> 'name') end,
    'promotions', (select coalesce(jsonb_agg(jsonb_build_object('id', x ->> 'id', 'code', x ->> 'code', 'name', x ->> 'name',
                     'discount', (x ->> 'discount')::integer, 'stackable', (x ->> 'stackable')::boolean)), '[]'::jsonb)
                   from jsonb_array_elements(v_applied) x),
    'code', case when code_p.id is null then null else code_p.code end,
    'code_status', v_code_status,
    'service_charge_percent', st.service_charge_percent, 'service_charge', v_svc,
    'vat_percent', st.vat_percent, 'vat', v_vat,
    'taxes_pending', (st.service_charge_percent is null or st.vat_percent is null),
    'total', v_total,
    'advance_percent', st.advance_percent,
    'advance_due', case when st.advance_percent is null then 0 else round(v_total * st.advance_percent / 100.0)::integer end);
end;
$$;

