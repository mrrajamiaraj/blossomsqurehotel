-- Housekeepers update their tasks (or claim unassigned ones); desk staff and
-- maintenance managers may update any. Starting a cleaning marks the room
-- "cleaning"; finishing marks it clean (or inspected for inspections).
create or replace function public.admin_update_task(p_task uuid, p_status text, p_notes text default null)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  t housekeeping_tasks%rowtype;
begin
  perform public._require('housekeeping.write');
  select * into t from housekeeping_tasks where id = p_task for update;
  if not found then
    raise exception 'NOT_FOUND';
  end if;
  if p_status not in ('open', 'in_progress', 'done', 'cancelled') then
    raise exception 'BAD_TASK';
  end if;
  if t.assigned_to is not null and t.assigned_to <> auth.uid()
     and not (public.has_permission('bookings.write') or public.has_permission('maintenance.manage')) then
    raise exception 'NOT_ALLOWED';
  end if;
  update housekeeping_tasks set
    status = p_status,
    assigned_to = coalesce(assigned_to, auth.uid()),
    notes = coalesce(nullif(left(trim(coalesce(p_notes, '')), 500), ''), notes),
    completed_at = case when p_status = 'done' then now() end,
    updated_at = now()
  where id = t.id;
  if t.kind = 'clean' and p_status = 'in_progress' then
    update rooms set housekeeping = 'cleaning' where id = t.room_id and housekeeping <> 'cleaning';
  elsif t.kind = 'clean' and p_status in ('open', 'cancelled') then
    update rooms set housekeeping = 'dirty' where id = t.room_id and housekeeping = 'cleaning';
  elsif p_status = 'done' and t.kind in ('clean', 'inspect') then
    update rooms set housekeeping = case when t.kind = 'clean' then 'clean' else 'inspected' end where id = t.room_id;
  end if;
end;
$$;

-- Desk staff and maintenance managers assign (or unassign) a task.
create or replace function public.admin_assign_task(p_task uuid, p_user uuid)
returns void
language plpgsql
security definer
set search_path = public, private
as $$
begin
  perform public._require('housekeeping.write');
  if not (public.has_permission('bookings.write') or public.has_permission('maintenance.manage')) then
    raise exception 'NOT_ALLOWED';
  end if;
  if p_user is not null and not exists (
    select 1 from staff s join private.role_permissions rp on rp.role_code = s.role
    where s.user_id = p_user and s.active and rp.permission_code = 'housekeeping.write') then
    raise exception 'NOT_FOUND';
  end if;
  update housekeeping_tasks set assigned_to = p_user, updated_at = now()
  where id = p_task and status in ('open', 'in_progress');
  if not found then
    raise exception 'NOT_FOUND';
  end if;
end;
$$;

-- Anyone on housekeeping reports a fault; maintenance managers are notified.
create or replace function public.report_maintenance_issue(p_room uuid, p_summary text, p_urgent boolean)
returns uuid
language plpgsql
security definer
set search_path = public
as $$
declare
  v_number text;
  v_id uuid;
  v_text text := left(trim(coalesce(p_summary, '')), 500);
begin
  perform public._require('housekeeping.write');
  select number into v_number from rooms where id = p_room;
  if v_number is null then
    raise exception 'NOT_FOUND';
  end if;
  if char_length(v_text) < 3 then
    raise exception 'BAD_TASK';
  end if;
  insert into housekeeping_tasks (room_id, kind, priority, notes, created_by)
  values (p_room, 'maintenance', case when coalesce(p_urgent, false) then 1 else 2 end, v_text, auth.uid())
  returning id into v_id;
  perform public._notify('maintenance.manage', 'housekeeping',
    case when coalesce(p_urgent, false) then 'Urgent repair: room ' else 'Repair needed: room ' end || v_number,
    v_text, '/admin/housekeeping');
  return v_id;
end;
$$;

-- The housekeeping board: every room with its status, whether a guest is in
-- it and today's movements, without guest names or booking details.
create or replace function public.housekeeping_board(p_day date default null)
returns table (room_id uuid, number text, floor text, room_type text, housekeeping text, out_of_service boolean,
               service_note text, occupied boolean, arriving boolean, departing boolean, blocked boolean,
               open_tasks integer, open_issues integer)
language plpgsql
stable
security definer
set search_path = public
as $$
declare
  v_day date := coalesce(p_day, public._today());
begin
  perform public._require('housekeeping.read');
  return query
    select r.id, r.number, r.floor, rt.name, r.housekeeping, r.out_of_service, r.service_note,
      exists (select 1 from booking_rooms br join bookings b on b.id = br.booking_id
              where br.room_id = r.id and b.status = 'checked_in'),
      exists (select 1 from booking_rooms br join bookings b on b.id = br.booking_id
              where br.room_id = r.id and br.check_in = v_day and b.status in ('pending', 'confirmed')),
      exists (select 1 from booking_rooms br join bookings b on b.id = br.booking_id
              where br.room_id = r.id and br.check_out = v_day and b.status = 'checked_in'),
      exists (select 1 from room_blocks k where k.room_id = r.id and k.released_at is null and k.starts_on <= v_day and k.ends_on > v_day),
      (select count(*)::integer from housekeeping_tasks t where t.room_id = r.id and t.status in ('open', 'in_progress') and t.kind <> 'maintenance'),
      (select count(*)::integer from housekeeping_tasks t where t.room_id = r.id and t.status in ('open', 'in_progress') and t.kind = 'maintenance')
    from rooms r join room_types rt on rt.id = r.room_type_id
    order by r.number;
end;
$$;

