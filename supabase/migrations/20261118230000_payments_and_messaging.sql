-- A guest reports a transfer they made (bank, bKash or Nagad, to the hotel's
-- published account). It is "pending" — not counted as paid — until staff
-- check it arrived.
create or replace function public.guest_submit_payment(p_token text, p_method text, p_amount integer, p_reference text, p_sender text)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  b         bookings%rowtype := public._booking_for_token(p_token);
  v_method  text;
  v_ref     text := upper(regexp_replace(coalesce(p_reference, ''), '\s', '', 'g'));
  v_pending integer;
  v_open    integer;
  v_id      uuid;
begin
  v_method := case p_method when 'bank_transfer' then 'bank' when 'bkash_manual' then 'bkash' when 'nagad_manual' then 'nagad' end;
  if v_method is null or not public._method_enabled(p_method) then
    raise exception 'METHOD_DISABLED';
  end if;
  if b.status not in ('pending', 'confirmed', 'checked_in') then
    raise exception 'LOCKED';
  end if;
  if v_ref !~ '^[A-Z0-9-]{6,40}$' then
    raise exception 'BAD_REFERENCE';
  end if;
  perform 1 from bookings where id = b.id for update;
  select count(*), coalesce(sum(amount_bdt), 0) into v_pending, v_open
  from payments where booking_id = b.id and status = 'pending';
  if v_pending >= 3 then
    raise exception 'TOO_MANY_PENDING';
  end if;
  if p_amount is null or p_amount < 1 or p_amount > (select total_bdt - amount_paid_bdt from bookings where id = b.id) - v_open then
    raise exception 'BAD_AMOUNT';
  end if;
  if exists (select 1 from payments where method = v_method and upper(reference) = v_ref and status in ('pending', 'confirmed')) then
    raise exception 'DUPLICATE_REFERENCE';
  end if;
  begin
    insert into payments (booking_id, amount_bdt, method, status, source, reference, sender, note)
    values (b.id, p_amount, v_method, 'pending', 'guest', v_ref, nullif(left(trim(coalesce(p_sender, '')), 60), ''),
            'Reported by the guest; awaiting verification')
    returning id into v_id;
  exception when unique_violation then
    raise exception 'DUPLICATE_REFERENCE';
  end;
  perform public._log(b.id, 'payment', jsonb_build_object('reported', p_amount, 'method', v_method, 'reference', v_ref));
  perform public._notify('payments.record', 'payment', 'Payment to verify: ' || b.reference,
    v_method || ' ' || v_ref || ', ৳' || p_amount, '/admin/bookings/' || b.reference);
  return jsonb_build_object('id', v_id, 'status', 'pending', 'amount', p_amount, 'method', v_method, 'reference', v_ref);
end;
$$;

-- Staff confirm (it arrived) or reject (it didn't) a reported transfer.
create or replace function public.admin_verify_payment(p_payment uuid, p_accept boolean, p_note text)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  p payments%rowtype;
  v_note text := nullif(left(trim(coalesce(p_note, '')), 200), '');
begin
  perform public._require('payments.record');
  select * into p from payments where id = p_payment for update;
  if not found then
    raise exception 'NOT_FOUND';
  end if;
  if p.status <> 'pending' or p.intent_id is not null then
    raise exception 'BAD_TRANSITION';
  end if;
  if not coalesce(p_accept, false) and char_length(coalesce(v_note, '')) < 3 then
    raise exception 'BAD_TRANSITION';
  end if;
  update payments set
    status = case when p_accept then 'confirmed' else 'failed' end,
    verified_by = auth.uid(), verified_at = now(), review_note = v_note,
    received_at = case when p_accept then now() else received_at end
  where id = p.id;
  if p_accept then
    update bookings set payment_due_at = null where id = p.booking_id and payment_due_at is not null;
  end if;
  perform public._log(p.booking_id, 'payment', jsonb_build_object(
    case when p_accept then 'verified' else 'rejected' end, p.amount_bdt, 'method', p.method, 'reference', p.reference, 'note', v_note));
end;
$$;

