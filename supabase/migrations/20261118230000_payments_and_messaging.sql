-- Claims due messages for sending. Stale claims (a worker that died) are
-- picked up again; messages out of attempts are failed.
create or replace function public.claim_messages(p_limit integer default 10)
returns setof message_outbox
language plpgsql
security definer
set search_path = public
as $$
declare
  m message_outbox%rowtype;
begin
  with dead as (
    update message_outbox set status = 'failed', locked_until = null, updated_at = now(),
           last_error = coalesce(last_error, 'Gave up after ' || attempts || ' attempts')
    where status = 'sending' and locked_until < now() and attempts >= max_attempts
    returning id
  )
  insert into message_events (message_id, kind, detail) select id, 'failed', '{"reason":"attempts exhausted"}' from dead;

  for m in
    with c as (
      select id from message_outbox
      where ((status = 'queued' and next_attempt_at <= now()) or (status = 'sending' and locked_until < now()))
        and attempts < max_attempts
      order by next_attempt_at, created_at
      limit least(greatest(coalesce(p_limit, 10), 1), 50)
      for update skip locked
    )
    update message_outbox o set status = 'sending', attempts = o.attempts + 1, locked_until = now() + interval '2 minutes', updated_at = now()
    from c where o.id = c.id
    returning o.*
  loop
    insert into message_events (message_id, kind, detail) values (m.id, 'attempt', jsonb_build_object('attempt', m.attempts));
    return next m;
  end loop;
end;
$$;

-- The worker's result for a claimed message. p_result: sent | retry | failed | unconfigured.
create or replace function public.complete_message(p_id uuid, p_result text, p_provider text, p_provider_message_id text, p_error text)
returns text
language plpgsql
security definer
set search_path = public
as $$
declare
  m message_outbox%rowtype;
  v_err text := nullif(left(coalesce(p_error, ''), 500), '');
begin
  select * into m from message_outbox where id = p_id for update;
  if not found then
    raise exception 'NOT_FOUND';
  end if;
  if m.status <> 'sending' then
    return 'ignored';
  end if;
  if p_result = 'sent' then
    update message_outbox set status = 'sent', sent_at = now(), locked_until = null, last_error = null, updated_at = now(),
           provider = left(p_provider, 30), provider_message_id = left(p_provider_message_id, 200)
    where id = m.id;
    insert into message_events (message_id, kind, detail) values (m.id, 'sent', jsonb_build_object('provider', p_provider, 'id', p_provider_message_id));
    return 'sent';
  elsif p_result = 'retry' and m.attempts < m.max_attempts then
    update message_outbox set status = 'queued', locked_until = null, last_error = v_err, updated_at = now(),
           next_attempt_at = now() + least(interval '6 hours', interval '1 minute' * power(4, m.attempts))
    where id = m.id;
    insert into message_events (message_id, kind, detail) values (m.id, 'retry', jsonb_build_object('error', v_err, 'attempt', m.attempts));
    return 'retry';
  elsif p_result = 'unconfigured' then
    update message_outbox set status = 'unconfigured', locked_until = null, last_error = v_err, updated_at = now(),
           attempts = greatest(m.attempts - 1, 0)
    where id = m.id;
    insert into message_events (message_id, kind, detail) values (m.id, 'unconfigured', jsonb_build_object('error', v_err));
    return 'unconfigured';
  elsif p_result in ('failed', 'retry') then
    update message_outbox set status = 'failed', locked_until = null, last_error = v_err, updated_at = now() where id = m.id;
    insert into message_events (message_id, kind, detail) values (m.id, 'failed', jsonb_build_object('error', v_err, 'attempt', m.attempts));
    return 'failed';
  end if;
  raise exception 'BAD_TRANSITION';
end;
$$;

-- A provider's delivery update (webhook), applied once per event.
-- p_status: delivered | opened | bounced | complained | failed.
create or replace function public.message_delivery_update(p_provider text, p_event_id text, p_provider_message_id text, p_status text, p_detail jsonb)
returns text
language plpgsql
security definer
set search_path = public
as $$
declare
  m message_outbox%rowtype;
  v_seen boolean;
begin
  insert into webhook_receipts (provider, event_id) values (p_provider, left(p_event_id, 200))
  on conflict do nothing
  returning true into v_seen;
  if v_seen is null then
    return 'replay';
  end if;
  select * into m from message_outbox where provider = p_provider and provider_message_id = p_provider_message_id for update;
  if not found then
    return 'unknown';
  end if;
  if p_status not in ('delivered', 'opened', 'bounced', 'complained', 'failed') then
    return 'ignored';
  end if;
  insert into message_events (message_id, kind, detail) values (m.id, p_status, coalesce(p_detail, '{}'));
  if p_status = 'delivered' and m.status in ('sent', 'sending') then
    update message_outbox set status = 'delivered', delivered_at = now(), updated_at = now() where id = m.id;
  elsif p_status in ('bounced', 'failed') and m.status in ('sent', 'sending', 'delivered') then
    update message_outbox set status = 'failed', updated_at = now(),
           last_error = left(coalesce(p_detail ->> 'reason', 'The provider reported it as ' || p_status), 500)
    where id = m.id;
  end if;
  return 'applied';
end;
$$;

/* ------------------------------------------------------- Staff: resend */

create or replace function public.admin_resend_message(p_id uuid)
returns uuid
language plpgsql
security definer
set search_path = public
as $$
declare
  m          message_outbox%rowtype;
  b          bookings%rowtype;
  v_to       text;
  v_id       uuid;
begin
  select * into m from message_outbox where id = p_id for update;
  if not found then
    raise exception 'NOT_FOUND';
  end if;
  perform public._require(case when m.booking_id is not null then 'bookings.write' else 'inquiries.manage' end);
  if m.status not in ('failed', 'unconfigured', 'skipped', 'cancelled') then
    raise exception 'RESEND_NOT_ALLOWED';
  end if;
  if exists (select 1 from message_outbox where resent_from = m.id) then
    raise exception 'ALREADY_RESENT';
  end if;
  -- At most three resends of the same message in a day.
  if (select count(*) from (
        with recursive chain as (
          select id, resent_from, created_at from message_outbox where id = m.id
          union all
          select o.id, o.resent_from, o.created_at from message_outbox o join chain c on o.id = c.resent_from
        ) select 1 from chain where resent_from is not null and created_at > now() - interval '24 hours') x) >= 3 then
    raise exception 'RESEND_LIMIT';
  end if;

  -- Today's contact details (they may have been corrected since).
  if m.booking_id is not null then
    select * into b from bookings where id = m.booking_id;
    if m.channel = 'email' then
      v_to := b.email;
    else
      if not coalesce((select whatsapp from messaging_consents where booking_id = b.id), false) then
        raise exception 'NO_CONSENT';
      end if;
      v_to := public._wa_number(b.phone);
    end if;
  else
    v_to := (select email from inquiries where id = m.inquiry_id);
  end if;
  if nullif(trim(coalesce(v_to, '')), '') is null then
    raise exception 'NO_RECIPIENT';
  end if;

  insert into message_outbox (channel, template, booking_id, inquiry_id, payment_id, recipient, data, status, resent_from, created_by)
  values (m.channel, m.template, m.booking_id, m.inquiry_id, m.payment_id, v_to, m.data, 'queued', m.id, auth.uid())
  returning id into v_id;
  insert into message_events (message_id, kind, detail, actor) values (m.id, 'resent', jsonb_build_object('new_message', v_id), auth.uid());
  insert into message_events (message_id, kind, detail, actor) values (v_id, 'queued', jsonb_build_object('resent_from', m.id), auth.uid());
  if m.booking_id is not null then
    perform public._log(m.booking_id, 'message', jsonb_build_object('resent', m.template, 'channel', m.channel));
  end if;
  return v_id;
end;
$$;

/* ======================================================= Reconciliation */

create or replace function public.admin_payment_reconciliation(p_from date, p_to date)
returns jsonb
language plpgsql
stable
security definer
set search_path = public
as $$
declare
  v_from timestamptz;
  v_to   timestamptz;
begin
  perform public._require('payments.read');
  if p_from is null or p_to is null or p_to < p_from or p_to - p_from > 366 then
    raise exception 'BAD_DATES';
  end if;
  v_from := p_from::timestamp at time zone 'Asia/Dhaka';
  v_to := (p_to + 1)::timestamp at time zone 'Asia/Dhaka';
  return jsonb_build_object(
    'from', p_from, 'to', p_to,
    'by_method', coalesce((
      select jsonb_agg(x order by x ->> 'method') from (
        select jsonb_build_object('method', m.method,
          'received', coalesce((select sum(amount_bdt) from payments where method = m.method and status = 'confirmed' and received_at >= v_from and received_at < v_to), 0),
          'count', (select count(*) from payments where method = m.method and status = 'confirmed' and received_at >= v_from and received_at < v_to),
          'pending', coalesce((select sum(amount_bdt) from payments where method = m.method and status = 'pending'), 0),
          'refunded', coalesce((select sum(amount_bdt) from refunds where method = m.method and status = 'completed' and completed_at >= v_from and completed_at < v_to), 0)) as x
        from (select distinct method from payments union select distinct method from refunds) m
      ) t), '[]'::jsonb),
    'exceptions', coalesce((
      select jsonb_agg(e order by e ->> 'at' desc) from (
        -- Reported transfers nobody has checked for a day.
        select jsonb_build_object('kind', 'unverified_transfer', 'reference', b.reference, 'amount', p.amount_bdt, 'at', p.created_at,
                                  'detail', p.method || ' ' || coalesce(p.reference, ''), 'payment_id', p.id) as e
        from payments p join bookings b on b.id = p.booking_id
        where p.status = 'pending' and p.created_at < now() - interval '24 hours'
        union all
        -- Gateway said "paid" with a different amount.
        select jsonb_build_object('kind', 'amount_mismatch', 'reference', b.reference, 'amount', i.amount_bdt, 'at', i.updated_at,
                                  'detail', i.provider || ' ' || coalesce(i.provider_ref, ''))
        from payment_intents i join bookings b on b.id = i.booking_id
        where i.failure_reason = 'amount_mismatch' and i.updated_at >= v_from and i.updated_at < v_to
        union all
        -- Succeeded intents without a ledger entry (should never happen).
        select jsonb_build_object('kind', 'missing_ledger_entry', 'reference', b.reference, 'amount', i.amount_bdt, 'at', i.updated_at,
                                  'detail', i.provider || ' ' || coalesce(i.provider_ref, ''))
        from payment_intents i join bookings b on b.id = i.booking_id
        where i.status = 'succeeded' and not exists (select 1 from payments p where p.intent_id = i.id and p.status = 'confirmed')
        union all
        -- Notifications that were refused (bad signature, unverified, rejected).
        select jsonb_build_object('kind', 'gateway_' || g.outcome, 'reference', b.reference, 'amount', g.amount_bdt, 'at', g.received_at,
                                  'detail', g.provider || ' event ' || g.event_id)
        from payment_gateway_events g left join payment_intents i on i.id = g.intent_id left join bookings b on b.id = i.booking_id
        where g.outcome in ('bad_signature', 'unverified', 'rejected', 'mismatch') and g.received_at >= v_from and g.received_at < v_to
        union all
        -- More received than the booking costs.
        select jsonb_build_object('kind', 'overpaid', 'reference', b.reference, 'amount', b.amount_paid_bdt - b.total_bdt, 'at', b.updated_at,
                                  'detail', 'paid ' || b.amount_paid_bdt || ' of ' || b.total_bdt)
        from bookings b where b.amount_paid_bdt > b.total_bdt and b.status not in ('cancelled', 'no_show')
        union all
        -- Cancelled with money still held and no refund under way.
        select jsonb_build_object('kind', 'refund_owed', 'reference', b.reference, 'amount', b.amount_paid_bdt, 'at', coalesce(b.cancelled_at, b.updated_at),
                                  'detail', 'cancelled with ' || b.amount_paid_bdt || ' paid')
        from bookings b
        where b.status in ('cancelled', 'no_show') and b.amount_paid_bdt > 0
          and not exists (select 1 from refunds r where r.booking_id = b.id and r.status in ('requested', 'approved'))
      ) t), '[]'::jsonb));
end;
$$;

