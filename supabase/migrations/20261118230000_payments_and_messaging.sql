-- Intents: only real gateway providers, only methods the hotel offers, never
-- more than the balance still open (counting other live intents).
create or replace function public.create_payment_intent(p_reference text, p_amount integer, p_provider text, p_idempotency_key text)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  b bookings%rowtype;
  i payment_intents%rowtype;
  v_live integer;
begin
  select * into i from payment_intents where idempotency_key = p_idempotency_key;
  if found then
    return jsonb_build_object('intent_id', i.id, 'amount', i.amount_bdt, 'status', i.status, 'replayed', true);
  end if;
  if p_provider not in ('bkash', 'nagad', 'card') then
    raise exception 'BAD_PAYMENT_OPTION';
  end if;
  if not public._method_enabled(p_provider) then
    raise exception 'METHOD_DISABLED';
  end if;
  select * into b from bookings where reference = upper(trim(p_reference)) for update;
  if not found then
    raise exception 'NOT_FOUND';
  end if;
  if b.status not in ('pending', 'confirmed', 'checked_in') then
    raise exception 'LOCKED';
  end if;
  select coalesce(sum(amount_bdt), 0) into v_live from payment_intents
  where booking_id = b.id and status = 'created' and expires_at > now();
  if p_amount is null or p_amount <= 0 or p_amount > b.total_bdt - b.amount_paid_bdt - v_live then
    raise exception 'BAD_AMOUNT';
  end if;
  insert into payment_intents (booking_id, provider, amount_bdt, idempotency_key)
  values (b.id, p_provider, p_amount, p_idempotency_key)
  returning * into i;
  return jsonb_build_object('intent_id', i.id, 'amount', i.amount_bdt, 'status', i.status, 'reference', b.reference,
                            'expires_at', i.expires_at, 'replayed', false);
end;
$$;

-- The ledger update for a verified gateway result. Idempotent; the amount
-- must match; a success that arrives after the intent expired is still
-- applied (the guest's money was taken).
create or replace function public.apply_payment_callback(p_provider text, p_intent uuid, p_provider_ref text, p_status text, p_amount integer)
returns text
language plpgsql
security definer
set search_path = public
as $$
declare
  i payment_intents%rowtype;
begin
  select * into i from payment_intents where id = p_intent and provider = p_provider for update;
  if not found then
    raise exception 'NOT_FOUND';
  end if;
  if p_status not in ('succeeded', 'failed', 'cancelled') then
    raise exception 'BAD_TRANSITION';
  end if;
  if i.status not in ('created', 'expired') then
    return case when i.status = p_status and i.provider_ref is not distinct from p_provider_ref then 'duplicate' else 'ignored' end;
  end if;
  if i.status = 'expired' and p_status <> 'succeeded' then
    return 'ignored';
  end if;
  if p_status = 'succeeded' and p_amount is distinct from i.amount_bdt then
    update payment_intents set status = 'failed', failure_reason = 'amount_mismatch', provider_ref = p_provider_ref, updated_at = now() where id = i.id;
    perform public._log(i.booking_id, 'payment', jsonb_build_object('gateway', p_provider, 'result', 'amount_mismatch', 'expected', i.amount_bdt, 'got', p_amount));
    return 'mismatch';
  end if;
  update payment_intents set status = p_status, provider_ref = p_provider_ref, updated_at = now() where id = i.id;
  if p_status = 'succeeded' then
    insert into payments (booking_id, amount_bdt, method, status, source, reference, note, intent_id)
    values (i.booking_id, i.amount_bdt, case p_provider when 'card' then 'card' when 'bkash' then 'bkash' when 'nagad' then 'nagad' else 'online' end,
            'confirmed', 'gateway', left(p_provider_ref, 80), 'Online payment via ' || p_provider, i.id);
    update bookings set payment_due_at = null where id = i.booking_id and payment_due_at is not null;
  end if;
  perform public._log(i.booking_id, 'payment', jsonb_build_object('gateway', p_provider, 'result', p_status, 'amount', i.amount_bdt));
  return 'applied';
end;
$$;

-- Records a gateway notification (once), then applies it only if its
-- signature was valid AND the server confirmed it with the gateway.
-- Returns: replay | bad_signature | unverified | applied | duplicate | ignored | mismatch | rejected.
create or replace function public.record_gateway_event(
  p_provider text, p_event_id text, p_intent uuid, p_provider_ref text, p_status text, p_amount integer,
  p_payload_sha256 text, p_signature_ok boolean, p_verified boolean
)
returns text
language plpgsql
security definer
set search_path = public
as $$
declare
  v_event bigint;
  v_out   text;
begin
  insert into payment_gateway_events (provider, event_id, intent_id, provider_ref, status, amount_bdt, signature_ok, verified, payload_sha256)
  values (p_provider, left(p_event_id, 200), (select id from payment_intents where id = p_intent), left(p_provider_ref, 120),
          left(p_status, 30), p_amount, coalesce(p_signature_ok, false), coalesce(p_verified, false), p_payload_sha256)
  on conflict (provider, event_id) do nothing
  returning id into v_event;
  if v_event is null then
    return 'replay';
  end if;
  if not coalesce(p_signature_ok, false) then
    v_out := 'bad_signature';
  elsif not coalesce(p_verified, false) then
    v_out := 'unverified';
  else
    begin
      v_out := public.apply_payment_callback(p_provider, p_intent, p_provider_ref, p_status, p_amount);
    exception when others then
      v_out := 'rejected';
    end;
  end if;
  update payment_gateway_events set outcome = v_out where id = v_event;
  return v_out;
end;
$$;

