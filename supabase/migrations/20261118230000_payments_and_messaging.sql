-- A Bangladeshi mobile number in international form for WhatsApp, or null.
create or replace function public._wa_number(p_phone text)
returns text language sql immutable set search_path = public as $$
  select case
    when d ~ '^01[3-9][0-9]{8}$' then '88' || d
    when d ~ '^8801[3-9][0-9]{8}$' then d
    when d ~ '^1[3-9][0-9]{8}$' then '880' || d
    when d ~ '^[1-9][0-9]{9,14}$' and d !~ '^0' and char_length(d) >= 11 then d
  end
  from (select regexp_replace(coalesce(p_phone, ''), '\D', '', 'g') as d) x;
$$;

