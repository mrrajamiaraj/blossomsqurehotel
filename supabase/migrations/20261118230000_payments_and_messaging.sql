-- Where pg_cron is available (Supabase): expire unpaid gateway intents every
-- five minutes; queue tomorrow's pre-arrival reminders at 10:00 Dhaka time.
do $$
begin
  begin
    create extension if not exists pg_cron;
  exception when others then
    raise notice 'pg_cron not available: %', sqlerrm;
    return;
  end;
  execute $cron$select cron.schedule('bsq-payment-intents', '*/5 * * * *', 'select public.expire_payment_intents();')$cron$;
  execute $cron$select cron.schedule('bsq-pre-arrival', '0 4 * * *', 'select public.enqueue_pre_arrival_reminders();')$cron$;
exception when others then
  raise notice 'Could not schedule payment/messaging jobs: %', sqlerrm;
end;
$$;
