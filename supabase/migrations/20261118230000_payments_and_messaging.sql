create or replace function public._enqueue_message(
  p_channel text, p_template text, p_booking uuid, p_inquiry uuid, p_payment uuid, p_recipient text, p_data jsonb, p_dedupe text
)
returns uuid
language plpgsql
security definer
set search_path = public
as $$
declare
  v_id uuid;
  v_status text := case when nullif(trim(coalesce(p_recipient, '')), '') is null then 'skipped' else 'queued' end;
begin
  insert into message_outbox (channel, template, booking_id, inquiry_id, payment_id, recipient, data, dedupe_key, status, last_error)
  values (p_channel, p_template, p_booking, p_inquiry, p_payment, nullif(trim(coalesce(p_recipient, '')), ''), coalesce(p_data, '{}'),
          p_dedupe, v_status, case when v_status = 'skipped' then 'No ' || case p_channel when 'email' then 'email address' else 'WhatsApp number' end || ' on file' end)
  on conflict (dedupe_key) do nothing
  returning id into v_id;
  if v_id is not null then
    insert into message_events (message_id, kind, detail) values (v_id, case when v_status = 'skipped' then 'skipped' else 'queued' end, '{}');
  end if;
  return v_id;
end;
$$;

-- Queues a guest message about a booking: email always (skipped without an
-- address); WhatsApp only with the guest's consent.
create or replace function public._message_guest(p_booking uuid, p_template text, p_dedupe text, p_payment uuid, p_extra jsonb)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  b bookings%rowtype;
  v_data jsonb;
begin
  select * into b from bookings where id = p_booking;
  if not found then
    return;
  end if;
  v_data := public._booking_message_data(b.id) || coalesce(p_extra, '{}');
  perform public._enqueue_message('email', p_template, b.id, null, p_payment, b.email, v_data, 'email:' || p_dedupe);
  if p_template <> 'payment_failure'
     and coalesce((select whatsapp from messaging_consents where booking_id = b.id), false) then
    perform public._enqueue_message('whatsapp', p_template, b.id, null, p_payment, public._wa_number(b.phone), v_data, 'wa:' || p_dedupe);
  end if;
end;
$$;

