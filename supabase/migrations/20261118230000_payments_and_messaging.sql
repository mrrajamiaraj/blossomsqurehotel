-- Everything an invoice shows. p_full_contact: staff see the guest's contact
-- details; the guest's own copy shows them masked.
create or replace function public._invoice_json(p_booking uuid, p_full_contact boolean)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  b   bookings%rowtype;
  inv invoices%rowtype;
begin
  select * into b from bookings where id = p_booking;
  if not found then
    raise exception 'NOT_FOUND';
  end if;
  inv := public._invoice_number(b.id);
  return jsonb_build_object(
    'number', inv.number, 'issued_at', inv.issued_at, 'generated_at', now(),
    'reference', b.reference, 'status', b.status, 'source', b.source, 'created_at', b.created_at,
    'guest', jsonb_build_object(
      'name', b.guest_name,
      'email', case when p_full_contact then b.email else public._mask_email(b.email) end,
      'phone', case when p_full_contact then b.phone else public._mask_phone(b.phone) end,
      'country', b.country),
    'stay', jsonb_build_object('check_in', b.check_in, 'check_out', b.check_out, 'nights', b.check_out - b.check_in,
                               'adults', b.adults, 'children', b.children, 'rooms', b.rooms),
    'lines', coalesce((
      select jsonb_agg(jsonb_build_object('room_type', rt.name, 'rate_plan', rp.name, 'nights', br.price_detail,
                                          'subtotal', coalesce(br.subtotal_bdt, 0)) order by br.line_no, br.id)
      from booking_rooms br join room_types rt on rt.id = br.room_type_id left join rate_plans rp on rp.id = br.rate_plan_id
      where br.booking_id = b.id), '[]'::jsonb),
    'subtotal', coalesce(b.subtotal_bdt, b.total_bdt),
    'discount', coalesce(b.discount_bdt, 0),
    'promotions', coalesce((
      select jsonb_agg(jsonb_build_object('name', pr.name, 'code', pr.code, 'discount', bp.discount_bdt) order by bp.discount_bdt desc)
      from booking_promotions bp join promotions pr on pr.id = bp.promotion_id where bp.booking_id = b.id), '[]'::jsonb),
    'service_charge_percent', b.price_detail -> 'service_charge_percent', 'service_charge', coalesce(b.service_charge_bdt, 0),
    'vat_percent', b.price_detail -> 'vat_percent', 'vat', coalesce(b.vat_bdt, 0),
    'taxes_pending', coalesce((b.price_detail ->> 'taxes_pending')::boolean, true),
    'total', b.total_bdt,
    'payments', coalesce((
      select jsonb_agg(jsonb_build_object('id', p.id, 'receipt_no', p.receipt_no, 'received_at', p.received_at, 'method', p.method,
                                          'reference', p.reference, 'amount', p.amount_bdt, 'status', p.status) order by p.received_at, p.created_at)
      from payments p where p.booking_id = b.id and p.status in ('confirmed', 'pending')), '[]'::jsonb),
    'refunds', coalesce((
      select jsonb_agg(jsonb_build_object('completed_at', r.completed_at, 'method', r.method, 'reference', r.reference, 'amount', r.amount_bdt)
                       order by r.completed_at)
      from refunds r where r.booking_id = b.id and r.status = 'completed'), '[]'::jsonb),
    'paid', coalesce((select sum(amount_bdt) from payments where booking_id = b.id and status = 'confirmed'), 0),
    'refunded', coalesce((select sum(amount_bdt) from refunds where booking_id = b.id and status = 'completed'), 0),
    'pending', coalesce((select sum(amount_bdt) from payments where booking_id = b.id and status = 'pending'), 0),
    'balance', greatest(b.total_bdt - b.amount_paid_bdt, 0),
    'credit', greatest(b.amount_paid_bdt - b.total_bdt, 0));
end;
$$;

