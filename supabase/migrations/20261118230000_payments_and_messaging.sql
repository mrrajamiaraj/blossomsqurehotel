-- Payments and guest messaging.
--
--   Payment methods   which methods the hotel offers (Settings); gateways are
--                     also gated by server credentials in the app.
--   Transfers         guests report a bank / bKash / Nagad transfer with its
--                     transaction ID; it counts as paid only after staff verify
--                     it. Duplicate transaction IDs are refused.
--   Gateways          every notification is stored once per (provider, event)
--                     (replay protection) with its signature and server-side
--                     verification result; only verified events reach the
--                     ledger, through the existing idempotent callback.
--   Receipts          every confirmed payment gets a receipt number.
--   Invoices          one numbered invoice per booking, built from the stored
--                     price breakdown and the ledger.
--   Messaging         an outbox of guest emails / WhatsApp messages, queued by
--                     triggers (booking created / confirmed / changed /
--                     cancelled, payments, enquiries) and a daily pre-arrival
--                     job; claimed by the app's worker with retries and
--                     backoff; delivery updates from provider webhooks (replay
--                     protected); staff can resend failed messages.
--   Reconciliation    totals per method and a list of exceptions to check.
--
-- Error codes: METHOD_DISABLED, BAD_REFERENCE, DUPLICATE_REFERENCE,
-- TOO_MANY_PENDING, RESEND_NOT_ALLOWED, ALREADY_RESENT, NO_RECIPIENT,
-- NO_CONSENT, RESEND_LIMIT (plus existing NOT_FOUND, BAD_AMOUNT, NOT_ALLOWED,
-- BAD_TRANSITION, LOCKED, ACCESS_EXPIRED).
--
-- Rollback: supabase/rollbacks/20261118230000_payments_and_messaging.down.sql
-- (generated by scripts/gen-payments-rollback.mts, verified by tests/db/payments-rollback.test.ts).

